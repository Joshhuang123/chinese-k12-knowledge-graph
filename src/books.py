#!/usr/bin/env python3
"""
册次映射层。

**为什么要单独抽出来**：归一化层和校验层都需要「这个册次排在第几位」，
但册次编码本身不是跨学科统一的命名空间：

- 物理的初三是一整本「九年级」，数学/化学拆成「九上」「九下」
- 同一个 `9` 在不同学科里指的时间跨度不一样

原来这个映射写在 `normalize.py` 里、用 `list(BOOKS)` 的插入顺序当排名，
于是「九年级」(rank 17) 排在「九上」(18) 之前 —— 而它其实是覆盖整个
初三学年的一本书。单学科内看不出来，一旦引入跨学科边就会大面积误报倒挂。

三个概念，别混：

| 字段 | 用途 | 口径 |
|---|---|---|
| `grade` | 画面分层（build_viz 决定节点落在锥形哪一层） | 沿用既有口径，**本层不改** |
| `rank` | 同一学科内排先后（九上早于九下） | 全局教材序列 |
| `year` | 跨学科比学年（必修一、必修二同属高一） | 学年序 |

`grade` 与 `year` 在高中段本来就不一致：必修二/选必一的 grade 是 11，
但真实学年都是高一。**那是画面分层的既有选择，不在这里偷偷改**——
改了会移动画面上的点，那是另一件事。year 只用于跨学科比较。

数据来源：人教版（2019 新课标）教材册次。
"""

# 学段 → 显示名
STAGE_ZH = {"小学": "小学", "初中": "初中", "高中": "高中"}

# 全局教材序列：跨学科可比的自然顺序
# 九年级（物理整年本）放在九上之前 —— 它从初三学年开始，和九上同期
GLOBAL_ORDER = [
    "1a", "1b", "2a", "2b", "3a", "3b", "4a", "4b", "5a", "5b", "6a", "6b",
    "7a", "7b", "8a", "8b",
    "9", "9a", "9b",
    "bx1", "bx2", "bx3",
    "xzxbx1", "xzxbx2", "xzxbx3",
]

# 册次编码 → (学段, grade 画面分层, 显示名)
# grade 这一列沿用归一化层的历史口径，本层不改动它。
BOOKS = {
    "1a": ("小学", 1, "一上"), "1b": ("小学", 1, "一下"),
    "2a": ("小学", 2, "二上"), "2b": ("小学", 2, "二下"),
    "3a": ("小学", 3, "三上"), "3b": ("小学", 3, "三下"),
    "4a": ("小学", 4, "四上"), "4b": ("小学", 4, "四下"),
    "5a": ("小学", 5, "五上"), "5b": ("小学", 5, "五下"),
    "6a": ("小学", 6, "六上"), "6b": ("小学", 6, "六下"),
    "7a": ("初中", 7, "七上"), "7b": ("初中", 7, "七下"),
    "8a": ("初中", 8, "八上"), "8b": ("初中", 8, "八下"),
    "9":  ("初中", 9, "九年级"), "9a": ("初中", 9, "九上"), "9b": ("初中", 9, "九下"),
    "bx1": ("高中", 10, "必修一"), "bx2": ("高中", 11, "必修二"), "bx3": ("高中", 12, "必修三"),
    "xzxbx1": ("高中", 11, "选必一"), "xzxbx2": ("高中", 12, "选必二"), "xzxbx3": ("高中", 12, "选必三"),
}

# 学年序：跨学科比较只认这个。人教 2019 新课标下
#   高一 = 必修第一册 + 必修第二册
#   高二 = 必修第三册 + 选择性必修第一册
#   高三 = 选择性必修第二册 + 选择性必修第三册
YEAR = {
    "1a": 1, "1b": 1, "2a": 2, "2b": 2, "3a": 3, "3b": 3,
    "4a": 4, "4b": 4, "5a": 5, "5b": 5, "6a": 6, "6b": 6,
    "7a": 7, "7b": 7, "8a": 8, "8b": 8,
    "9": 9, "9a": 9, "9b": 9,
    "bx1": 10, "bx2": 10, "bx3": 11,
    "xzxbx1": 11, "xzxbx2": 12, "xzxbx3": 12,
}

RANK = {b: i for i, b in enumerate(GLOBAL_ORDER)}

UNKNOWN_RANK = 99
UNKNOWN_YEAR = 99


def lookup(book):
    """→ (学段, grade, 显示名)，未登记的册次不静默编造。"""
    if book in BOOKS:
        return BOOKS[book]
    raise KeyError(f"册次 {book!r} 未登记在 books.py 的 BOOKS 里 —— "
                   f"请先确认它属于哪一册，别让它静默变成「未知」")


def rank(book):
    return RANK.get(book, UNKNOWN_RANK)


def year(book):
    return YEAR.get(book, UNKNOWN_YEAR)


def is_reversed(from_book, to_book, same_subject):
    """先修方出现在更晚的册次里没有？

    同一学科：比 rank。九上确实早于九下。
    跨学科：只比学年。不同学科在同一学年里的推进节奏本来就不同 ——
    「数学九上早于物理九年级」这种比较在跨学科语境下没有意义，
    把整年本和上下册硬排出先后，只会产生假警报。
    """
    if same_subject:
        return rank(from_book) > rank(to_book)
    return year(from_book) > year(to_book)
